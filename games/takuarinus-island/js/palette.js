const FALLBACK = '#B8B0C8';
const warned = new Set();

/** 配色。未登録のキー（文字列）は中間色を返す */
export const PALETTE = new Proxy(BASE, {
  get(target, key, recv) {
    if (typeof key !== 'string' || key in target) return Reflect.get(target, key, recv);
    if (key === 'then' || key === 'toJSON' || key.startsWith('__')) return undefined;
    // 「黒」を名乗るキー（例: 黒い額縁）は黒にする
    if (/black/i.test(key)) return '#000000';
    if (!warned.has(key) && typeof window !== 'undefined') {
      warned.add(key);
      console.warn('palette に無い色:', key);
    }
    return FALLBACK;
  },
});
